import { access, cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const managedContractsRoot = path.join(repoRoot, 'contracts', 'managed');
const generatedRoot = path.join(repoRoot, 'web', 'src', 'generated');
const publicRoot = path.join(repoRoot, 'web', 'public');

// Circuit names are unique across both contracts, so their keys and zkir
// files share one public directory and one FetchZkConfigProvider base URL.
const contracts = ['veilpledge', 'veilgate'];

const emptyDeployment = {
  network: 'preprod',
  contractAddress: '',
  transactionHash: '',
  blockHeight: 0,
  deployedAt: '',
};

async function exists(filePath) {
  try {
    await access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function requireCompiledContracts() {
  for (const contract of contracts) {
    const contractModule = path.join(managedContractsRoot, contract, 'contract', 'index.js');
    if (!(await exists(contractModule))) {
      throw new Error(
        `Compact artifacts for ${contract} are missing. Run \`npm run compile\` before preparing the web app.`,
      );
    }
  }
}

async function copyContractModules() {
  for (const contract of contracts) {
    const destination = path.join(generatedRoot, contract);
    await rm(destination, { force: true, recursive: true });
    await mkdir(destination, { recursive: true });

    for (const fileName of ['index.js', 'index.js.map', 'index.d.ts']) {
      const source = path.join(managedContractsRoot, contract, 'contract', fileName);
      if (await exists(source)) {
        await cp(source, path.join(destination, fileName));
      }
    }
  }
}

async function copyZkArtifacts() {
  for (const directory of ['keys', 'zkir']) {
    const destination = path.join(publicRoot, directory);
    await rm(destination, { force: true, recursive: true });
    await mkdir(destination, { recursive: true });

    for (const contract of contracts) {
      await cp(path.join(managedContractsRoot, contract, directory), destination, {
        recursive: true,
      });
    }
  }
}

async function readDeployment(fileName, required) {
  const deploymentPath = path.join(repoRoot, 'deployments', fileName);

  if (!(await exists(deploymentPath))) {
    if (required) {
      throw new Error(
        `A production Pages build requires a verified deployments/${fileName} record.`,
      );
    }
    return emptyDeployment;
  }

  const parsed = JSON.parse(await readFile(deploymentPath, 'utf8'));
  if (
    parsed.network !== 'preprod' ||
    !/^[0-9a-f]{64}$/i.test(parsed.contractAddress) ||
    !/^[0-9a-f]{64}$/i.test(parsed.transactionHash) ||
    !Number.isSafeInteger(parsed.blockHeight) ||
    parsed.blockHeight <= 0 ||
    typeof parsed.deployedAt !== 'string' ||
    !Number.isFinite(Date.parse(parsed.deployedAt))
  ) {
    throw new Error(`deployments/${fileName} is not a valid Preprod deployment record.`);
  }
  return parsed;
}

async function writeDeploymentModule() {
  const requireDeployment = process.env.REQUIRE_PREPROD_DEPLOYMENT === '1';
  const [pledge, gate] = await Promise.all([
    readDeployment('preprod.json', requireDeployment),
    // Matches deploymentRecordFile() in src/deploy-target.ts, which keeps the
    // network first so deployments/ stays sorted by network.
    readDeployment('preprod-veilgate.json', false),
  ]);

  await mkdir(generatedRoot, { recursive: true });
  const source = [
    '// Generated by scripts/prepare-web-assets.mjs. Do not edit.',
    `export const PREPROD_DEPLOYMENT = ${JSON.stringify(pledge, null, 2)} as const;`,
    '',
    `export const VEILGATE_PREPROD_DEPLOYMENT = ${JSON.stringify(gate, null, 2)} as const;`,
    '',
  ].join('\n');
  await writeFile(path.join(generatedRoot, 'deployment.ts'), source, 'utf8');
}

await requireCompiledContracts();
await Promise.all([copyContractModules(), copyZkArtifacts(), writeDeploymentModule()]);

process.stdout.write('Prepared browser contract modules, ZK artifacts, and public Preprod metadata.\n');
